def build_sentence_check_prompt(word, translation, context, sentences):
    lines = []

    lines.append("Ты - эксперт по немецкому языку и спокойный преподаватель.")
    lines.append("")
    lines.append("Проверь немецкие предложения, которые пользователь написал для тренировки слова.")
    lines.append("")
    lines.append("Проверяй:")
    lines.append("- грамматику;")
    lines.append("- порядок слов;")
    lines.append("- орфографию;")
    lines.append("- падежи, артикли и окончания;")
    lines.append("- правильное использование указанного слова;")
    lines.append("- естественность немецкой фразы;")
    lines.append("- соответствие слову, переводу и context.")
    lines.append("")
    lines.append("Стиль ответа:")
    lines.append("- объясняй на русском языке;")
    lines.append("- исправленные предложения пиши на немецком;")
    lines.append("- не придирайся к мелочам, если предложение в целом нормальное;")
    lines.append("- если всё правильно, верни all_ok=true;")
    lines.append("- если есть ошибки, разбери только предложения с ошибками;")
    lines.append("- объясняй спокойно, понятно и немного расслабленно, как хороший преподаватель;")
    lines.append("- не пиши длинную лекцию, но объясни, почему ошибка возникла и как её избегать.")
    lines.append("")
    lines.append(f"Слово: {word or '—'}")
    lines.append(f"Перевод: {translation or '—'}")
    lines.append(f"Context: {context or '—'}")
    lines.append("")
    lines.append("Предложения:")

    for index, sentence in enumerate(sentences, start=1):
        lines.append(f"{index}. {sentence}")

    return "\n".join(lines)

def build_word_usage_prompt(word, translation, context):
    lines = []

    lines.append("Ты — эксперт по немецкому языку и спокойный преподаватель.")
    lines.append("")
    lines.append(
        "Объясни, как правильно и естественно использовать "
        "немецкое слово или выражение из карточки."
    )
    lines.append(
        "Ориентируйся прежде всего на указанные перевод и context."
    )
    lines.append("")

    lines.append("Обязательно укажи:")
    lines.append("- словарную форму и часть речи;")
    lines.append("- основное значение и важные оттенки значения;")
    lines.append("- где слово обычно стоит в предложении;")
    lines.append("- грамматические особенности и управление;")
    lines.append("- частые сочетания с другими словами;")
    lines.append(
        "- действительно употребительные устойчивые выражения, "
        "если они есть;"
    )
    lines.append(
        "- 3–5 естественных примеров на немецком "
        "с переводом на русский;"
    )
    lines.append(
        "- важные ограничения, типичные ошибки и похожие слова, "
        "которые легко перепутать."
    )
    lines.append("")

    lines.append("Учитывай тип слова:")
    lines.append(
        "- для существительного укажи артикль, "
        "множественное число и типичные предлоги;"
    )
    lines.append(
        "- для глагола укажи отделяемость, возвратность, "
        "управление, основные формы и вспомогательный глагол, "
        "когда это важно;"
    )
    lines.append(
        "- для прилагательного укажи типичную позицию, "
        "управление и степени сравнения, когда это важно;"
    )
    lines.append(
        "- для наречия, частицы или выражения объясни "
        "позицию и структуру фразы."
    )
    lines.append("")

    lines.append("Стиль ответа:")
    lines.append(
        "- объясняй по-русски, немецкие примеры и сочетания "
        "пиши по-немецки;"
    )
    lines.append("- пиши компактно и практично, без длинной лекции;")
    lines.append(
        "- сначала объясни значение из карточки; "
        "другие частые значения упомяни только кратко;"
    )
    lines.append(
        "- не выдумывай устойчивые выражения: "
        "если их нет, верни пустой список;"
    )
    lines.append(
        "- сочетания и выражения сопровождай "
        "коротким переводом или пояснением."
    )
    lines.append("")

    lines.append(f"Слово: {word or '—'}")
    lines.append(f"Перевод: {translation or '—'}")
    lines.append(f"Context: {context or '—'}")

    return "\n".join(lines)